// Comparison operators
 let a = 5;
 let b = 25;
 console.log("5 == 25 ", a == b); // false

// != means not equal to
console.log("5 != 25 ", a != b); // true

// === is used to compare different data types.
let c = "10";
let d = 10;
console.log("10 === 10 ", c === d); // false

// <,>.=
console.log("5 < 25 ", a < b); // true
